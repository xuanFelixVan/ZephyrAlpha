def fix_single_line_box_diagrams(text: str) -> str:
    """展开 ```\\n┌…``` 单行/多行框图（与 Data Layer / Research 脚本同构）。"""

    def repl(m: re.Match[str]) -> str:
        raw = m.group(0)
        inner = m.group(1)
        if not inner.startswith("┌"):
            return raw
        if (
            inner.count("\n") >= 1
            and "??" not in inner
            and "?└" not in inner
            and not re.search(r"┌[─]{15,}│\s+[\u4e00-\u9fffA-Za-z0-9]", inner)
        ):
            return raw
        inner = re.sub(r"(┌[─]{20,})\?(?=\n)", r"\1─┐\n│ ", inner, count=1)
        inner = re.sub(
            r"(┌[─]{20,})│(\s+)([\u4e00-\u9fffA-Za-z0-9])",
            r"\1┐\n│\2\3",
            inner,
            count=1,
        )
        inner = re.sub(r"(┌─+)\?\?", r"\1─┐\n│ ", inner, count=1)
        inner = inner.replace("?? ", "│ ")
        inner = re.sub(r"\?└(─+)\?", r"└\1┘", inner)
        inner = inner.replace(" ?├", "\n├")
        inner = inner.replace(" ?└", "\n└")
        return "```\n" + inner + "\n```"

    return re.sub(r"```\n(┌.*?)```", repl, text, flags=re.DOTALL)


def polish_multi_engine_diagram(text: str) -> str:
    """统一交易执行层示意图：行首孤立 `?` → `│`，并清理残留角符。"""

    def repl(m: re.Match[str]) -> str:
        raw = m.group(0)
        inner = m.group(1)
        if "统一交易执行层" not in inner:
            return raw
        if "?" not in inner:
            return raw
        old_inner = inner
        inner = re.sub(r"(?m)^\?\s+", "│ ", inner)
        inner = inner.replace("?│", "│")
        inner = inner.replace("??", "│")
        inner = inner.replace("? ┌", "\n┌")
        inner = inner.replace("? └", "\n└")
        inner = re.sub(r"\? \?", "  ", inner)
        inner = re.sub(r"\s+\?(?=\n|$)", "", inner)
        if inner == old_inner:
            return raw
        return "```\n" + inner + "\n```"

    return re.sub(r"```\n(┌.*?)```", repl, text, flags=re.DOTALL)


def fix_list_bullet_star(text: str) -> str:
    text = re.sub(r"^(\s*-\s+)\?\*\*", r"\1**", text, flags=re.MULTILINE)
    text = re.sub(r"^(\s*\d+\.\s+)\?\*\*", r"\1**", text, flags=re.MULTILINE)
    text = re.sub(r"([^\n])- \?\*\*", r"\1\n- **", text)
    return text


def main() -> int:
    text = FP.read_text(encoding="utf-8-sig", errors="strict").replace("\r\n", "\n").replace("\r", "\n")
    orig = text

    text = keep_last_frontmatter(text).lstrip("\ufeff")
    for a, b in PAIRS:
        text = text.replace(a, b)

    text = text.replace("?br>", "<br>")
    text = text.replace("?br>", "<br>")

    # 在表格/示意图中残留的「适配?」→「适配器」（避免与「适配器」重复）
    text = text.replace("适配?", "适配器")
    text = text.replace("适配器器", "适配器")

    text = fix_single_line_box_diagrams(text)
    text = polish_multi_engine_diagram(text)
    text = fix_list_bullet_star(text)

    text = re.sub(r"\?(\d)", r"\1", text)
    text = re.sub(r"(\d)\?", r"\1", text)
    text = text.replace("PB?", "PB").replace("MB?", "MB").replace("毫秒?", "毫秒")

    if text != orig:
        if not text.endswith("\n"):
            text += "\n"
        FP.write_bytes(text.encode("utf-8-sig"))
        print("UPDATED")
    else:
        print("NO_CHANGE")
    return 0


