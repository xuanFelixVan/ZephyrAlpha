def polish_layer9_diagram(text: str) -> str:
    """Layer 9 大框图内残留 ?│ / ?? / 单字 ? 等噪声（在首轮展开后再清理）。"""

    def repl(m: re.Match[str]) -> str:
        raw = m.group(0)
        inner = m.group(1)
        if "Layer 9" not in inner and "研究与创新层" not in inner:
            return raw
        if "?" not in inner:
            return raw
        old_inner = inner
        inner = inner.replace("?│", "│")
        inner = inner.replace("??", "│")
        inner = inner.replace("? ┌", "\n┌")
        inner = inner.replace("? └", "\n└")
        inner = re.sub(r"\? \?", "  ", inner)
        for a, b in LAYER9_DIAGRAM_PAIRS:
            inner = inner.replace(a, b)
        inner = re.sub(r"\s+\?(?=\n|$)", "", inner)
        if inner == old_inner:
            return raw
        return "```\n" + inner + "\n```"

    return re.sub(r"```\n(┌.*?)```", repl, text, flags=re.DOTALL)


def fix_single_line_box_diagrams(text: str) -> str:
    def repl(m: re.Match[str]) -> str:
        raw = m.group(0)
        inner = m.group(1)
        if not inner.startswith("┌"):
            return raw
        if (
            inner.count("\n") >= 1
            and "??" not in inner
            and "?└" not in inner
            and not re.search(r"┌[─]{15,}│\s+[\u4e00-\u9fffA-Za-z0-9]", inner)
        ):
            return raw
        inner = re.sub(
            r"(┌[─]{20,})│(\s+)([\u4e00-\u9fffA-Za-z0-9])",
            r"\1┐\n│\2\3",
            inner,
            count=1,
        )
        inner = re.sub(r"(┌─+)\?\?", r"\1─┐\n│ ", inner, count=1)
        inner = inner.replace("?? ", "│ ")
        inner = re.sub(r"\?└(─+)\?", r"└\1┘", inner)
        inner = inner.replace(" ?├", "\n├")
        inner = inner.replace(" ?└", "\n└")
        return "```\n" + inner + "\n```"

    return re.sub(r"```\n(┌.*?)```", repl, text, flags=re.DOTALL)


def fix_list_bullet_star(text: str) -> str:
    text = re.sub(r"^(\s*-\s+)\?\*\*", r"\1**", text, flags=re.MULTILINE)
    text = re.sub(r"^(\s*\d+\.\s+)\?\*\*", r"\1**", text, flags=re.MULTILINE)
    text = re.sub(r"([^\n])- \?\*\*", r"\1\n- **", text)
    return text


