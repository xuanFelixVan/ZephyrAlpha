def _has_chinese(text: str) -> bool:
    """检测字符串是否包含中文字符。"""
    if not text:
        return False
    return any("\u4e00" <= ch <= "\u9fff" for ch in text)


def _strip_version_info(name: str) -> str:
    """去除名称中的版本信息（— v0.13.0 R181 等）。"""
    # 去除 " — vX.Y.Z RNNN" 后缀
    name = re.sub(r"\s*[—-]\s*v?\d+\.\d+\.\d+\s+R\d+.*$", "", name)
    # 去除 " — vX.Y.Z" 后缀
    name = re.sub(r"\s*[—-]\s*v?\d+\.\d+\.\d+.*$", "", name)
    # 去除尾部 " — anything"
    name = re.sub(r"\s*[—-]\s+.*$", "", name)
    return name.strip()


def _split_name(name: str) -> list[str]:
    """将英文名称拆分为单词列表。

    处理：
    - 空格分隔： "Training Dataset Manager" → ["Training", "Dataset", "Manager"]
    - 连字符： "Anti-Pattern" → ["Anti", "Pattern"]
    - 下划线： "stop_loss" → ["stop", "loss"]
    - 驼峰： "DatasetManager" → ["Dataset", "Manager"]
    - 字母数字混合： "A2a" → ["A2a"]（不拆分）
    """
    # 先按空格和连字符拆分
    parts = re.split(r"[\s\-_]+", name)
    # 再拆分驼峰
    words: list[str] = []
    for part in parts:
        if not part:
            continue
        # 专有名词不拆分（整体查词典）
        if part in _PROPER_NOUNS:
            words.append(part)
            continue
        # 优先匹配字母数字混合词（如 A2a, H1, E2e），避免拆分丢失
        # 然后拆分驼峰： "DatasetManager" → "Dataset" + "Manager"
        sub = re.findall(r"[A-Za-z]+\d+[A-Za-z]*|[A-Z]?[a-z]+|[A-Z]+(?=[A-Z]|$)|\d+", part)
        if sub:
            words.extend(sub)
        else:
            words.append(part)
    return words


def translate_name(name_en: str, module_path: str = "") -> str:
    """将英文名称翻译为中文。

    策略：
    1. 去除版本信息
    2. 拆分为单词
    3. 逐词查词典翻译
    4. 未匹配的词保留英文
    5. 中文词直接拼接（不加空格），英文词间加空格

    特殊处理：
    - __init__.py → "包入口"
    - Test 开头 → "X测试"（测试后置）
    - 全英文无匹配 → 从 module_path 的文件名派生
    """
    if not name_en:
        # 从 module_path 派生
        if module_path:
            fname = module_path.rsplit("/", 1)[-1].rsplit("\\", 1)[-1]
            if fname == "__init__.py":
                return "包入口"
            if fname.endswith(".py"):
                fname = fname[:-3]
            name_en = fname.replace("_", " ").replace("-", " ")
        else:
            return ""

    # 特殊处理：__init__.py
    if module_path and module_path.endswith("__init__.py"):
        return "包入口"

    # 去除版本信息
    name_en = _strip_version_info(name_en)

    # 特殊处理：Test 开头的测试文件
    words = _split_name(name_en)
    if words and words[0].lower() == "test":
        rest = " ".join(words[1:])
        # 不传 module_path，避免从 test_xxx 文件名派生导致重复"测试"
        translated_rest = translate_name(rest, "")
        if translated_rest:
            return f"{translated_rest}测试"
        return "测试"

    # 逐词翻译
    translated: list[str] = []
    has_chinese_part = False
    for word in words:
        # 尝试精确匹配（保留大小写）
        cn = _TERM_MAP.get(word)
        if cn is None:
            # 尝试首字母大写
            cn = _TERM_MAP.get(word.capitalize())
        if cn is None:
            # 尝试小写
            cn = _TERM_MAP.get(word.lower())
        if cn is not None:
            if _has_chinese(cn):
                has_chinese_part = True
            translated.append(cn)
        else:
            # 未匹配，保留英文
            translated.append(word)

    result = "".join(translated) if has_chinese_part else " ".join(translated)

    # 如果结果不含中文（全英文未匹配），从 module_path 文件名派生
    if not _has_chinese(result) and module_path:
        fname = module_path.rsplit("/", 1)[-1].rsplit("\\", 1)[-1]
        if fname.endswith(".py"):
            fname = fname[:-3]
        if fname == "__init__":
            return "包入口"
        # snake_case 文件名翻译
        fname_words = fname.replace("-", "_").split("_")
        fname_translated: list[str] = []
        for fw in fname_words:
            cn = _TERM_MAP.get(fw) or _TERM_MAP.get(fw.capitalize()) or _TERM_MAP.get(fw.lower())
            fname_translated.append(cn if cn else fw)
        result = (
            "".join(fname_translated) if any(_has_chinese(t) for t in fname_translated) else " ".join(fname_translated)
        )

    return result.strip()


def main() -> int:
    """Entry point: parse args, run logic, return exit code."""
    parser = argparse.ArgumentParser(description="批量修复 module_translation_registry.yaml 中 name_zh 不含中文的条目")
    parser.add_argument("--dry-run", action="store_true", help="预览模式，不写文件")
    parser.add_argument("--execute", action="store_true", help="执行写入")
    parser.add_argument("--limit", type=int, default=0, help="限制处理条目数（0=全部）")
    args = parser.parse_args()

    if not args.dry_run and not args.execute:
        print("请指定 --dry-run 或 --execute")
        return 1

    import yaml

    # 1. 读取 YAML，识别需要修复的条目
    with open(_YAML_PATH, encoding="utf-8") as f:
        data = yaml.safe_load(f)

    entries = data.get("entries", [])
    fixes: dict[str, str] = {}  # module_path → new name_zh
    skipped = 0

    for i, entry in enumerate(entries):
        if args.limit and len(fixes) >= args.limit:
            break
        zh = (entry.get("name_zh") or "").strip()
        en = (entry.get("name_en") or "").strip()
        mp = (entry.get("module_path") or "").strip()

        # name_zh 已含中文 → 跳过
        if zh and _has_chinese(zh):
            skipped += 1
            continue

        # name_zh 不含中文或为空 → 需要修复
        new_zh = translate_name(en, mp)
        if new_zh and _has_chinese(new_zh) and new_zh != zh:
            fixes[mp] = new_zh
        elif new_zh and not _has_chinese(new_zh):
            # 翻译后仍无中文，保留原值
            skipped += 1

    print(f"总条目: {len(entries)}")
    print(f"已含中文（跳过）: {skipped}")
    print(f"需修复: {len(fixes)}")
    print()

    if args.dry_run:
        # 预览前 50 条
        print("=== 预览（前 50 条）===")
        for mp, new_zh in list(fixes.items())[:50]:
            # 找原 en
            orig_en = ""
            for e in entries:
                if (e.get("module_path") or "").strip() == mp:
                    orig_en = (e.get("name_en") or "").strip()
                    break
            print(f"  {mp}")
            print(f"    en: {orig_en}")
            print(f"    zh: {new_zh}")
        if len(fixes) > 50:
            print(f"  ... 共 {len(fixes)} 条（仅展示前 50 条）")
        return 0

    # 2. 逐行替换 YAML 中的 name_zh 行
    with open(_YAML_PATH, encoding="utf-8") as f:
        lines = f.readlines()

    # 建立 module_path → 行号映射
    current_module_path: str | None = None
    replacements_made = 0
    new_lines: list[str] = []

    for line in lines:
        # 检测 module_path 行
        mp_match = re.match(r"^- module_path:\s*(.+?)\s*$", line)
        if mp_match:
            current_module_path = mp_match.group(1).strip()
        elif re.match(r"^  module_path:\s*(.+?)\s*$", line):
            current_module_path = re.match(r"^  module_path:\s*(.+?)\s*$", line).group(1).strip()

        # 检测 name_zh 行
        zh_match = re.match(r"^(  name_zh:)\s*(.*)$", line)
        if zh_match and current_module_path and current_module_path in fixes:
            prefix = zh_match.group(1)
            new_val = fixes[current_module_path]
            # 需要引号的情况：含特殊字符
            if any(
                c in new_val
                for c in [":", "#", "{", "}", "[", "]", ",", "&", "*", "!", "|", ">", "'", '"', "%", "@", "`"]
            ):
                new_line = f'{prefix} "{new_val}"\n'
            else:
                new_line = f"{prefix} {new_val}\n"
            new_lines.append(new_line)
            replacements_made += 1
            continue

        new_lines.append(line)

    # 3. 写入文件
    with open(_YAML_PATH, "w", encoding="utf-8") as f:
        f.writelines(new_lines)

    print(f"已写入 {replacements_made} 条 name_zh 修复到 {_YAML_PATH}")
    print(f"剩余未翻译（词典无匹配）: {len(fixes) - replacements_made}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
