def _read_existing_facets(conn, node_id: int) -> dict:
    """读取节点现有 facets（read 阶段），返回 dict（空则 {}）。"""
    with conn.cursor(cursor_factory=RealDictCursor) as cur:
        cur.execute("SELECT facets FROM decision_nodes WHERE node_id = %s", (node_id,))
        row = cur.fetchone()
    if not row:
        raise ValueError(f"node_id {node_id} 不存在")
    facets = row["facets"]
    if not facets:
        return {}
    if isinstance(facets, dict):
        return facets
    # psycopg2 通常已解析 JSONB 为 dict，此处兜底
    import json
    try:
        return json.loads(facets)
    except (json.JSONDecodeError, TypeError):
        return {}


def backfill(dry_run: bool = False) -> int:
    """对 213 节点执行读-改-写合并 plain_zh。

    :param dry_run: True 仅打印预览不写 DB
    :return: EXIT_PASS 成功 / EXIT_ERROR 失败
    """
    total = len(PLAIN_ZH_DRAFTS)
    print(f"[INFO] 待处理节点数: {total}（dry_run={dry_run}）")

    conn = get_decisiongraph_pg_connection()
    updated = 0
    skipped = 0
    errors = 0
    try:
        for node_id, plain_zh in PLAIN_ZH_DRAFTS.items():
            try:
                existing = _read_existing_facets(conn, node_id)
                old_plain = existing.get("plain_zh")
                # 读-改-写合并：只动 plain_zh 键，保留其他键
                merged = dict(existing)
                merged["plain_zh"] = plain_zh

                if dry_run:
                    tag = "[SKIP]" if old_plain == plain_zh else "[UPDATE]"
                    if old_plain and old_plain != plain_zh:
                        print(f"{tag} node {node_id}: plain_zh 覆盖更新（旧值长度 {len(old_plain or '')}）")
                    elif old_plain == plain_zh:
                        print(f"{tag} node {node_id}: plain_zh 已存在且相同，跳过")
                        skipped += 1
                    else:
                        print(f"{tag} node {node_id}: 新增 plain_zh（{plain_zh[:30]}…）")
                    updated += 1
                else:
                    if old_plain == plain_zh:
                        skipped += 1
                        continue
                    op_update_node_field(
                        conn, node_id=node_id, field="facets", value=merged, dry_run=False
                    )
                    updated += 1
            except ValueError as e:
                print(f"[ERROR] node {node_id}: {e}", file=sys.stderr)
                errors += 1
            except Exception as e:  # noqa: BLE001
                print(f"[ERROR] node {node_id}: 写入失败 {e}", file=sys.stderr)
                errors += 1
    finally:
        conn.close()

    action = "预览" if dry_run else "写入"
    print(f"\n[{'OK' if errors == 0 else 'WARN'}] {action}完成: 更新 {updated}，跳过 {skipped}，错误 {errors}，总计 {total}")
    return EXIT_ERROR if errors > 0 else EXIT_PASS


def main() -> int:
    """Entry point: parse args, run logic, return exit code."""
    parser = argparse.ArgumentParser(
        description="一次性补齐 213 决策节点的 plain_zh 大白话简介（读-改-写合并，幂等）",
    )
    parser.add_argument("--dry-run", action="store_true", help="仅预览不写 DB")
    args = parser.parse_args()
    return backfill(dry_run=args.dry_run)


if __name__ == "__main__":
    sys.exit(main())
