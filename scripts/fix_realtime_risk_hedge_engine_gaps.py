def replace_arch_block(t: str) -> str:
    # 原文 2.1 是空 fence
    needle = "### 2.1 系统架构?\n```\n\n### 2.2 核心子系统设?"
    if needle in t:
        return t.replace(
            needle,
            """### 2.1 系统架构

```mermaid
graph TB
  subgraph Inputs[输入层]
    POS[组合持仓/权重] --> MON[实时风险监控]
    MKT[市场数据/因子数据] --> MON
    BENCH[基准/行业分类] --> MON
  end

  MON --> ASSESS[风险评估与阈值判断]
  ASSESS --> WARN[预警生成]
  WARN --> GEN[对冲策略生成]
  GEN --> ORD[对冲订单生成]
  ORD --> EXEC[对冲执行]
  EXEC --> EVAL[效果监控与评估]
  EVAL --> ADJ[动态对冲调整]
  ADJ --> REP[报告生成]

  EVAL --> MON
```

### 2.2 核心子系统设计""",
        )
    return t


def fix_dataflow_block(t: str) -> str:
    t = t.replace("组合数据 ?风险计算 ?风险评估 ?预警生成 ?对冲策略 ?订单生成", "组合数据 → 风险计算 → 风险评估 → 预警生成 → 对冲策略 → 订单生成")
    t = t.replace("    ?          ?          ?          ?          ?          ?", "    ↓          ↓          ↓          ↓          ↓          ↓")
    t = t.replace("?对冲执行 ?效果监控 ?动态调??报告生成", "对冲执行 → 效果监控 → 动态调整 → 报告生成")
    t = t.replace("    ?          ?          ?          ?", "    ↓          ↓          ↓          ↓")
    return t


def main() -> int:
    t = FP.read_text(encoding="utf-8-sig", errors="strict").replace("\r\n", "\n").replace("\r", "\n")
    orig = t
    t = replace_arch_block(t)
    t = fix_dataflow_block(t)
    for a, b in PAIRS:
        t = t.replace(a, b)
    t = t.replace("\n?\n", "\n\n")
    t = t.replace("- ?", "- ")
    if t != orig:
        if not t.endswith("\n"):
            t += "\n"
        FP.write_bytes(t.encode("utf-8-sig"))
        print("UPDATED")
    else:
        print("NO_CHANGE")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

