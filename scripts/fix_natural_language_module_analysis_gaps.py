def keep_real_frontmatter(text: str) -> str:
    marker = "\nmodule_id: NATURAL_LANGUAGE_MODULE_ANALYSIS_001"
    idx = text.find(marker)
    if idx == -1:
        return text.lstrip("\ufeff")
    start = text.rfind("---\n", 0, idx)
    if start == -1:
        return text.lstrip("\ufeff")
    return text[start:].lstrip("\ufeff")


