def main() -> int:
    text = FP.read_text(encoding="utf-8-sig", errors="strict").replace("\r\n", "\n").replace("\r", "\n")
    orig = text

    text = keep_real_frontmatter(text)

    # 拆开被挤压在同一行的引用块字段
    text = re.sub(r"(完整分析)\s*>\s*(\*\*索引\*\*:)", r"\1\n> \2", text)

    for a, b in PAIRS:
        text = text.replace(a, b)

    # 通用：清理 “用户? / 系统??” 这类对话符号残片（保留问号语义时不动）
    text = re.sub(r"(?m)^用户\?", "用户：", text)
    text = re.sub(r"(?m)^系统\?\?", "系统：", text)
    text = re.sub(r"(?m)^系统\?", "系统：", text)

    # 清理紧贴数字的问号（例如 ?026）
    text = re.sub(r"\?(\d)", r"\1", text)
    text = re.sub(r"(\d)\?", r"\1", text)

    if text != orig:
        if not text.endswith("\n"):
            text += "\n"
        FP.write_bytes(text.encode("utf-8-sig"))
        print("UPDATED")
    else:
        print("NO_CHANGE")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

