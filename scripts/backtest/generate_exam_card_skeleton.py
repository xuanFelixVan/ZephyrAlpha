"""TDM 环节考试卡骨架生成器——186 节点全覆盖机生考卷骨架（方案 §5/§6，D5 拍板）。

读 config/trading_decision_map.yaml 的 nodes（真源）→ 在
docs/03_modules/_domain_backtest/exam_cards/<flow>/<layer>/ 下机生每节点一张默认卡族骨架
（一卡一文件）。默认卡族按被考环节性质映射（方案 §4 四族）：
  portfolio_flow → shadow（影子卡·组合族）
  sensor → calibration（校准卡·传感器族）
  aggregation → ablation（消融卡·聚合族）
  gate / stage → comparison（对照卡·机制族）
  cross_cutting → shadow（影子卡·组合族）

only-add 语义：已存在的机生卡只在 tdm 派生块漂移时重渲染（人填字段保留）；
手工卡（无 generated 标）永不触碰；任何文件永不删除。

幂等策略：渲染纯确定性（无时间戳；tdm.effective_from 作日期锚；键序=模板固定序；
yaml.safe_dump sort_keys=False + 宽度 120）。重跑零 diff；--check 只报告不写。

用法:
    python scripts/backtest/generate_exam_card_skeleton.py            # 生成/同步
    python scripts/backtest/generate_exam_card_skeleton.py --check    # 只报告漂移
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

from zephyr.shared.io.file_utils import safe_write_text
from zephyr.shared.io.paths import REPO_ROOT

TDM_PATH = REPO_ROOT / "config" / "trading_decision_map.yaml"
CARDS_ROOT = REPO_ROOT / "docs" / "03_modules" / "_domain_backtest" / "exam_cards"

FAMILY_BY_NODE_TYPE = {
    "sensor": "calibration",
    "aggregation": "ablation",
    "gate": "comparison",
    "stage": "comparison",
    "cross_cutting": "shadow",
}
FAMILY_BY_FLOW_OVERRIDE = {
    "portfolio_flow": "shadow",
}
FAMILY_ZH = {
    "calibration": "校准卡",
    "comparison": "对照卡",
    "ablation": "消融卡",
    "shadow": "影子卡",
}
STATUS_EMPTY = "empty"
GENERATED_KEY = "generated"
CARD_SEQ = "01"

_HEADER = (
    "# [GENERATED by MOD-BT-244 generate_exam_card_skeleton] 机生卡骨架：判据门柱留空，\n"
    "# 预注册时填写假设/窗口/分桶/门柱并置 status=preregistered（冻结起点，事后挪门柱=作废）。\n"
    "# 本文件由生成器 only-add 维护：手工卡请另建文件（无 generated 标即受保护，永不被冲）。\n"
)


class _ToolError(RuntimeError):
    """工具级异常：路径等敏感面入 details 字段不入消息文本（5.99.20 MSG-EXPOSURE 处方）。"""

    def __init__(self, msg: str, details: dict | None = None):
        super().__init__(msg)
        self.details = details or {}


def default_family(node: dict) -> str:
    """默认卡族：flow 覆盖优先（组合层全影子），否则按 node_type 映射（方案 §4）。"""
    flow = node.get("flow", "")
    if flow in FAMILY_BY_FLOW_OVERRIDE:
        return FAMILY_BY_FLOW_OVERRIDE[flow]
    node_type = node.get("node_type", "")
    family = FAMILY_BY_NODE_TYPE.get(node_type)
    if family is None:
        raise RuntimeError(f"node {node.get('node_id', '?')} node_type={node_type!r} 无默认卡族映射（fail-closed）")
    return family


def render_card(node: dict, tdm_meta: dict, human: dict | None = None) -> str:
    """渲染单张骨架卡（确定性：模板键序，禁时间戳）。human=已有卡的人填字段（同步时保留）。"""
    human = human or {}
    lineage_human = human.get("lineage") if isinstance(human.get("lineage"), dict) else {}
    node_id = node["node_id"]
    family = default_family(node)
    card_id = f"{node_id}/{family}/{CARD_SEQ}"
    card = {
        "schema_version": "1.0",
        "card_id": card_id,
        "node_id": node_id,
        "family": family,
        GENERATED_KEY: True,
        "title_zh": f"{node.get('name_zh', node_id)}·{FAMILY_ZH[family]}（骨架）",
        # —— 预注册面（骨架留空；填写=冻结起点）——
        "hypothesis": human.get("hypothesis"),
        "window": human.get("window"),
        "buckets": human.get("buckets"),
        "pillars": human.get("pillars"),
        "target": human.get("target"),
        "status": human.get("status", STATUS_EMPTY),
        # —— lineage 四链指针（卡→run_id→成绩册行→confidence 回写位）——
        "lineage": {
            "card": f"docs/03_modules/_domain_backtest/exam_cards/{node.get('flow')}/{node.get('layer')}/{node_id}__{family}.yaml",
            "run_id": lineage_human.get("run_id"),
            "score_row": lineage_human.get("score_row"),
            "confidence_writeback": f"TDM.nodes.{node_id}.confidence",
        },
        # —— TDM 派生块（同步时唯一允许更新的人不可编辑区）——
        "tdm": {
            "map_id": tdm_meta.get("map_id", "TDMAP-001"),
            "effective_from": tdm_meta.get("effective_from"),
            "flow": node.get("flow"),
            "layer": node.get("layer"),
            "node_type": node.get("node_type"),
            "market": node.get("market"),
            "decision_question": node.get("decision_question"),
            "module_ref": node.get("module_ref"),
            "module_id": node.get("module_id"),
            "confidence_at_gen": node.get("confidence"),
            "purpose_tag": node.get("purpose_tag"),
        },
    }
    body = yaml.safe_dump(card, allow_unicode=True, sort_keys=False, width=120)
    return _HEADER + body


def load_tdm(tdm_path: Path = TDM_PATH) -> tuple[list[dict], dict]:
    data = yaml.safe_load(Path(tdm_path).read_text(encoding="utf-8"))
    if not isinstance(data, dict):
        raise _ToolError("TDM 解析失败或为空", {"path": str(tdm_path)})
    nodes = data.get("nodes")
    if not nodes:
        raise _ToolError("TDM 无 nodes 或为零节点", {"path": str(tdm_path)})
    for n in nodes:
        for key in ("node_id", "flow", "layer"):
            if not n.get(key):
                raise _ToolError("TDM 节点缺必填键（fail-closed）", {"key": key, "node_id": n.get("node_id", "?")})
    meta = {"map_id": data.get("map_id"), "effective_from": data.get("effective_from")}
    return nodes, meta


def card_path(node: dict, cards_root: Path = CARDS_ROOT) -> Path:
    family = default_family(node)
    return cards_root / node["flow"] / node["layer"] / f"{node['node_id']}__{family}.yaml"


def _load_human_fields(path: Path) -> dict:
    """从既有卡提取人填字段（同步时保留）；非机生卡返回 None（保护跳过）。"""
    data = yaml.safe_load(path.read_text(encoding="utf-8"))
    if not isinstance(data, dict) or data.get(GENERATED_KEY) is not True:
        return None
    return {
        "hypothesis": data.get("hypothesis"),
        "window": data.get("window"),
        "buckets": data.get("buckets"),
        "pillars": data.get("pillars"),
        "target": data.get("target"),
        "status": data.get("status", STATUS_EMPTY),
        "lineage": data.get("lineage") or {},
    }


def run(
    check: bool = False, tdm_path: Path = TDM_PATH, cards_root: Path = CARDS_ROOT, repo_root: Path = REPO_ROOT
) -> dict:
    nodes, tdm_meta = load_tdm(tdm_path)
    created: list[str] = []
    synced: list[str] = []
    identical: list[str] = []
    protected: list[str] = []
    for node in nodes:
        path = card_path(node, cards_root)
        if path.exists():
            human = _load_human_fields(path)
            if human is None:
                protected.append(str(path))
                continue
            rendered = render_card(node, tdm_meta, human=human)
            disk = path.read_text(encoding="utf-8")
            if disk == rendered:
                identical.append(str(path))
                continue
            if check:
                synced.append(f"DRIFT {path}")
                continue
            result = safe_write_text(path, rendered, repo_root=repo_root)
            if not result.written and not Path(str(result.path)).exists():
                raise _ToolError("safe_write_text 失败", {"path": str(path), "result": str(result)})
            synced.append(str(path))
        else:
            if check:
                continue
            path.parent.mkdir(parents=True, exist_ok=True)
            result = safe_write_text(path, render_card(node, tdm_meta), repo_root=repo_root)
            if not result.written and not Path(str(result.path)).exists():
                raise _ToolError("safe_write_text 失败", {"path": str(path), "result": str(result)})
            created.append(str(path))

    if check:
        summary = {
            "mode": "check",
            "tdm_nodes": len(nodes),
            "drift": len([s for s in synced if s.startswith("DRIFT")]),
            "missing": sum(1 for n in nodes if not card_path(n, cards_root).exists()),
            "identical": len(identical),
            "protected_manual": len(protected),
        }
        return summary

    # 写后自校验：全量重渲染零 diff + 覆盖率 100% + only-add（无删除）；受保护手工卡跳过
    for node in nodes:
        path = card_path(node, cards_root)
        if not path.exists():
            raise _ToolError("写后自校验失败：机生卡缺失", {"path": str(path)})
        human = _load_human_fields(path)
        if human is None:
            continue  # 手工卡占据槽位：生成器零接触，机生一致性自校验不适用
        rendered = render_card(node, tdm_meta, human=human)
        if path.read_text(encoding="utf-8") != rendered:
            raise _ToolError("写后自校验失败：重渲染零 diff 不成立", {"path": str(path)})
    summary = {
        "mode": "write",
        "tdm_nodes": len(nodes),
        "created": len(created),
        "synced": len(synced),
        "identical": len(identical),
        "protected_manual": len(protected),
        "coverage": f"{len(created) + len(synced) + len(identical) + len(protected)}/{len(nodes)}",
    }
    return summary


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="只报告漂移不写（CI/门用）")
    args = parser.parse_args()
    summary = run(check=args.check)
    print(summary)
    if args.check and (summary["drift"] or summary["missing"]):
        return 1
    return 0


if __name__ == "__main__":  # noqa: m11-perm-manual-legitimate  人工CLI设计如此（同域MOD-BT-197先例）：按TDM变更/分数册更新/逐卡开考人工触发，非永久自动系统面
    sys.exit(main())
