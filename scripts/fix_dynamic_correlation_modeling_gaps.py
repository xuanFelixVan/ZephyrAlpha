def replace_arch_block(t: str) -> str:
    needle = "### 2.1 系统架构?\n```\n\n### 2.2 核心数据?\n```"
    if needle in t:
        return t.replace(
            needle,
            """### 2.1 系统架构

```mermaid
graph TB
  subgraph In[输入层]
    R[市场收益率数据] --> P[数据预处理]
  end

  P --> G[单资产 GARCH 拟合]
  G --> RES[标准化残差计算]
  RES --> DCC[DCC 相关性估计]
  DCC --> COV[动态协方差矩阵]
  DCC --> REG[相关性范式检测/突变检测]
  REG --> OUT[预警/报告/下游风控与优化]
```

### 2.2 核心数据流
```""",
        )
    return t


def main() -> int:
    t = FP.read_text(encoding="utf-8-sig", errors="strict").replace("\r\n", "\n").replace("\r", "\n")
    orig = t
    t = replace_arch_block(t)
    for a, b in PAIRS:
        t = t.replace(a, b)
    t = t.replace("\n?\n", "\n\n").replace("- ?", "- ")
    if t != orig:
        if not t.endswith("\n"):
            t += "\n"
        FP.write_bytes(t.encode("utf-8-sig"))
        print("UPDATED")
    else:
        print("NO_CHANGE")
    return 0


