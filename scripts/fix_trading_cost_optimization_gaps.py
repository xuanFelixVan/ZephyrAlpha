def replace_arch_block(t: str) -> str:
    needle = "### 2.1 系统架构?\n```\n\n### 2.2 核心数据?\n```"
    if needle in t:
        return t.replace(
            needle,
            """### 2.1 系统架构

```mermaid
graph TB
  subgraph Inputs[输入层]
    T[目标组合权重] --> D[交易需求计算]
    C[当前组合权重] --> D
    M[市场数据/约束] --> IMP[冲击成本估计]
  end

  D --> IMP[冲击成本估计]
  IMP --> SEL[执行算法选择]
  SEL --> PLAN[执行计划生成]
  PLAN --> COST[总成本计算]
  COST --> OUT[执行计划/成本估算输出]
```

### 2.2 核心数据流
```""",
        )
    return t


def fix_core_dataflow(t: str) -> str:
    t = t.replace("目标组合权重 - 当前组合权重", "目标组合权重 - 当前组合权重（计算交易需求）")
    t = t.replace("    ?输出执行计划与成本估?```", "    输出执行计划与成本估算\n```")
    return t


def main() -> int:
    t = FP.read_text(encoding="utf-8-sig", errors="strict").replace("\r\n", "\n").replace("\r", "\n")
    orig = t
    t = replace_arch_block(t)
    t = fix_core_dataflow(t)
    for a, b in PAIRS:
        t = t.replace(a, b)
    t = t.replace("\n?\n", "\n\n")
    t = t.replace("- ?", "- ")
    if t != orig:
        if not t.endswith("\n"):
            t += "\n"
        FP.write_bytes(t.encode("utf-8-sig"))
        print("UPDATED")
    else:
        print("NO_CHANGE")
    return 0


