def replace_arch_block(t: str) -> str:
    target = "### 2.1 系统架构?\n```"
    start = t.find(target)
    if start == -1:
        return t
    fence1 = t.find("```", start)
    if fence1 == -1:
        return t
    fence2 = t.find("```", fence1 + 3)
    if fence2 == -1:
        return t
    after = t[fence2 + 3 :]
    before = t[:start]
    mer = """### 2.1 系统架构

```mermaid
graph TB
  subgraph Inputs[输入层]
    R[策略收益率序列] --> PERF[绩效评估层]
    S[策略交易信号] --> FUSE[信号融合层]
    C[风险约束/预算] --> CONS[约束层]
  end

  subgraph Layers[分层与优化]
    PERF --> ALLOC[分层权重分配]
    CONS --> ALLOC
    FUSE --> COORD[策略协同优化]
    ALLOC --> COORD
  end

  subgraph Outputs[输出与监控]
    COORD --> W[权重输出]
    COORD --> FS[融合信号输出]
    COORD --> REP[绩效/风控报告]
    COORD --> AL[预警/监控]
  end
```
"""
    return before + mer + after


def main() -> int:
    t = FP.read_text(encoding="utf-8-sig", errors="strict").replace("\r\n", "\n").replace("\r", "\n")
    orig = t
    t = replace_arch_block(t)
    for a, b in PAIRS:
        t = t.replace(a, b)
    # 清理常见清单符号误码
    t = t.replace("\n?\n", "\n\n")
    t = t.replace("- ?","- ")
    if t != orig:
        if not t.endswith("\n"):
            t += "\n"
        FP.write_bytes(t.encode("utf-8-sig"))
        print("UPDATED")
    else:
        print("NO_CHANGE")
    return 0


