def replace_arch_blocks(t: str) -> str:
    # 2.1 系统架构：原文是空 fence，替换为 mermaid 框架图
    t = t.replace(
        "### 2.1 系统架构\n```\n\n### 2.2 核心数据流\n```",
        """### 2.1 系统架构

```mermaid
graph TB
  subgraph Inputs[输入层]
    P[组合权重/持仓] --> SYS[风险归因系统]
    B[基准权重] --> SYS
    M[风险模型（Barra/自研）] --> SYS
  end

  subgraph Core[核心计算]
    SYS --> F[因子风险归因]
    SYS --> I[行业风险归因]
    SYS --> A[资产风险归因]
    SYS --> BU[风险预算监控]
  end

  subgraph Output[输出层]
    F --> R[归因结果汇总]
    I --> R
    A --> R
    BU --> AL[预警信号]
    R --> REP[归因报告/可视化图表]
  end
```

### 2.2 核心数据流
```"""
    )
    return t


def main() -> int:
    t = FP.read_text(encoding="utf-8-sig", errors="strict").replace("\r\n", "\n").replace("\r", "\n")
    orig = t
    t = replace_arch_blocks(t)
    for a, b in PAIRS:
        t = t.replace(a, b)
    # 清理残留的独立 “?”（常见于清单勾选符号误码）
    t = t.replace("\n?\n", "\n\n")
    t = t.replace("- ?","- ")
    if t != orig:
        if not t.endswith("\n"):
            t += "\n"
        FP.write_bytes(t.encode("utf-8-sig"))
        print("UPDATED")
    else:
        print("NO_CHANGE")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

