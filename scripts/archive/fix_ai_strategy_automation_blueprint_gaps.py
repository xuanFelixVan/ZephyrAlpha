def remove_redundant_frontmatter(text: str) -> str:
    # 若文件开头有一个简化 YAML 头，紧接着又出现一个 BOM+--- 的真正 YAML 头，则移除第一个。
    # 形态：^--- ... ---\n\n﻿--- ...
    m = re.match(r"(?s)\\A---\\n.*?\\n---\\n\\s*\\n\\ufeff---\\n", text)
    if not m:
        # 有些文件是 "﻿---"（BOM 作为 U+FEFF）直接跟着
        m2 = re.match(r"(?s)\\A---\\n.*?\\n---\\n\\s*\\n\\ufeff?---\\n", text)
        if not m2:
            return text
        cut = m2.end() - len("---\n")
        return text[cut:]
    cut = m.end() - len("---\n")
    return text[cut:]


def fix_yaml_concatenation(text: str) -> str:
    # 修复被挤压在一行的 YAML 字段（高置信度）
    bad = (
        "standard_type: 专业机构级AI自动化蓝图专业机构级AI自动化蓝?"
        "applicable_scope: AI策略自动化集?compliance_level: 顶级专业标准"
    )
    good = "\n".join(
        [
            "standard_type: 专业机构级AI自动化蓝图",
            "applicable_scope: AI策略自动化集成",
            "compliance_level: 顶级专业标准",
        ]
    )
    return text.replace(bad, good)


