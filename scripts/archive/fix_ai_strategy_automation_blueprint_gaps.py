def main() -> int:
    text = FP.read_text(encoding="utf-8-sig", errors="strict").replace("\r\n", "\n").replace("\r", "\n")
    orig = text

    text = remove_redundant_frontmatter(text)
    text = fix_yaml_concatenation(text)

    for a, b in PAIRS:
        text = text.replace(a, b)

    # 进一步的结构化修复（保守正则）
    text = re.sub(r"评分\?(\d+)%", r"评分 ≥ \1%", text)
    text = re.sub(r"AI自动化率\?(\d+)%", r"AI自动化率 \1%", text)
    # 清理紧贴数字的孤立问号（对话示例里非常常见）
    text = re.sub(r"\?(\d)", r"\1", text)
    text = re.sub(r"(\d)\?", r"\1", text)
    # 列表项前缀的 “- ? / ?-” 残片
    text = re.sub(r"(?m)^\s*-\s*\?\s*", "- ", text)
    text = re.sub(r"(?m)^\s*\?\s*-\s*", "- ", text)
    # Phase 描述被挤在一行：拆行（仅在显式 Phase 前做拆分）
    text = text.replace("Phase 2 (Month 3-4):", "\nPhase 2 (Month 3-4):")
    text = text.replace("Phase 3 (Month 5-6):", "\nPhase 3 (Month 5-6):")
    text = text.replace("Phase 4 (Month 7-8):", "\nPhase 4 (Month 7-8):")
    text = text.replace("Phase 5 (Month 9-10):", "\nPhase 5 (Month 9-10):")

    # 轻量清理：常见“分隔符被挤在一行”的场景（仅处理明显模式）
    text = text.replace("> **核心理念**:", "> **核心理念**: ")
    text = re.sub(
        r"(\*\*核心理念\*\*:[^\n]*)> \*\*目标\*\*:",
        r"\1\n> **目标**:",
        text,
    )

    if text != orig:
        if not text.endswith("\n"):
            text += "\n"
        FP.write_bytes(text.encode("utf-8-sig"))
        print("UPDATED")
    else:
        print("NO_CHANGE")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

