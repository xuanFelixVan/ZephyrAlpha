    for line in text.split("\n"):
        if "| **P0-" in line:
            line = line.replace("| ?优先 |", "| P0 优先 |")
        elif "| **P1-" in line:
            line = line.replace("| ?0优先 |", "| P0 优先 |")
            line = line.replace("| ?1优先 |", "| P1 优先 |")
            line = line.replace("| ?优先 |", "| P1 优先 |")
        out.append(line)
    return "\n".join(out)


