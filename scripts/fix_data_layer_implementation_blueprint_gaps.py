def normalize_frontmatter(text: str) -> str:
    # 删除开头的模板化 YAML（2026-04-07 那段），保留后续真正 YAML
    # 形态：^--- ... ---\n\n﻿--- module_id: DATA_LAYER_IMPLEMENTATION_001 ...
    m = re.match(r"(?s)\\A---\\n.*?\\n---\\n\\s*\\n\\ufeff---\\nmodule_id:\\s*DATA_LAYER_IMPLEMENTATION_001", text)
    if not m:
        return text
    # 保留第二段的 "---\nmodule_id..."
    idx = text.find("\ufeff---\nmodule_id: DATA_LAYER_IMPLEMENTATION_001")
    if idx == -1:
        return text
    return text[idx + 1 :]  # 去掉 U+FEFF


