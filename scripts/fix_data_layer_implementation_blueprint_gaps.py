def fix_single_line_box_diagrams(text: str) -> str:
    """修复被压成单行的 ┌…┐ 示意框图：?? → 竖线、?└…? → 底边等。

    闭合围栏可能是「同一行 ┘```」或「换行后再 ```」，故用 (┌.*?)``` 非贪婪匹配。
    须先处理顶边 (┌─+)??，再 replace「?? 」，避免把顶角误换成竖线。
    """

    def repl(m: re.Match[str]) -> str:
        raw = m.group(0)
        inner = m.group(1)
        if not inner.startswith("┌"):
            return raw
        # 已展开且无待修片段时跳过，避免重复包裹导致非幂等
        if (
            inner.count("\n") >= 1
            and "??" not in inner
            and "?└" not in inner
            and not re.search(r"┌[─]{15,}│\s+[\u4e00-\u9fffA-Za-z0-9]", inner)
        ):
            return raw
        # 误修：顶边末端成「─│ + 标题」而非「─┐」换行「│ + 标题」
        inner = re.sub(
            r"(┌[─]{20,})│(\s+)([\u4e00-\u9fffA-Za-z0-9])",
            r"\1┐\n│\2\3",
            inner,
            count=1,
        )
        inner = re.sub(r"(┌─+)\?\?", r"\1─┐\n│ ", inner, count=1)
        inner = inner.replace("?? ", "│ ")
        inner = re.sub(r"\?└(─+)\?", r"└\1┘", inner)
        inner = inner.replace(" ?├", "\n├")
        inner = inner.replace(" ?└", "\n└")
        return "```\n" + inner + "\n```"

    return re.sub(r"```\n(┌.*?)```", repl, text, flags=re.DOTALL)


def fix_list_bullet_star(text: str) -> str:
    """将「- ?**标题**」恢复为「- **标题**」。"""
    text = re.sub(r"^(\s*-\s+)\?\*\*", r"\1**", text, flags=re.MULTILINE)
    text = re.sub(r"^(\s*\d+\.\s+)\?\*\*", r"\1**", text, flags=re.MULTILINE)
    # 「正文- ?**」应为换行后列表项
    text = re.sub(r"([^\n])- \?\*\*", r"\1\n- **", text)
    return text


def fix_squeezed_principles_lines(text: str) -> str:
    """展开「实施原则」中误插入的重复「行/块」与错误加粗边界。"""
    text = re.sub(r"(确保系统可运行)行+(?=2\.)", r"\1。\n", text)
    text = re.sub(r"2\.\s\*\*渐进式交付：", "2. **渐进式交付**：", text)
    text = re.sub(r"(每阶段交付可测试模块)块+(?=3\.)", r"\1。\n", text)
    text = re.sub(r"(系统可运行)行+。", r"\1。", text)
    text = re.sub(r"(可测试模块)块+。", r"\1。", text)
    text = re.sub(r"(可测试模块)块+(?=[，,])", r"\1", text)
    return text


def main() -> int:
    text = FP.read_text(encoding="utf-8-sig", errors="strict").replace("\r\n", "\n").replace("\r", "\n")
    orig = text

    # 历史误替换修复（可重复执行）
    text = text.replace("****技术架构**", "**技术架构**")

    text = normalize_frontmatter(text)
    text = fix_yaml_concatenation(text)

    for a, b in PAIRS:
        text = text.replace(a, b)

    text = fix_single_line_box_diagrams(text)
    text = fix_list_bullet_star(text)
    text = fix_squeezed_principles_lines(text)

    # 结构化清理：将紧贴数字的问号去掉（常见于“?0-20%/PB?/毫秒?”等）
    text = re.sub(r"\?(\d)", r"\1", text)
    text = re.sub(r"(\d)\?", r"\1", text)
    # 将形如 “PB?” “MB?” “毫秒?” 这种单位问号去掉（高置信度）
    text = text.replace("PB?", "PB").replace("MB?", "MB").replace("毫秒?", "毫秒")

    # 将连续的 '---' 归一为单个分隔（仅在文档开头的异常区）
    text = re.sub(r"(?m)\\A(---\\n){3,}", "---\n", text)

    if text != orig:
        if not text.endswith("\n"):
            text += "\n"
        FP.write_bytes(text.encode("utf-8-sig"))
        print("UPDATED")
    else:
        print("NO_CHANGE")
    return 0


